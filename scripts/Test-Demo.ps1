param(
    [string]$BaseUrl = 'http://localhost:8080',
    [string]$EnvFile = '.env.portfolio',
    [string]$ComposeProject = 'library-portfolio'
)

$ErrorActionPreference = 'Stop'
. "$PSScriptRoot/Import-LocalEnv.ps1" -Path $EnvFile
if ($env:MYSQL_DATABASE -notmatch '^library_(portfolio|demo)(_[a-z0-9]+)?$') {
    throw 'Use a dedicated library_portfolio or library_demo database, never existing business data.'
}
if ($BaseUrl -notmatch '^http://(localhost|127\.0\.0\.1):[0-9]+$') {
    throw 'This smoke test is restricted to an explicitly started local backend.'
}
Add-Type -AssemblyName System.Net.Http
$http = [System.Net.Http.HttpClient]::new()
$http.Timeout = [TimeSpan]::FromSeconds(15)
$checks = 0
function Assert-Equal($Actual, $Expected, [string]$Label) {
    if ($Actual -ne $Expected) { throw "$Label expected $Expected, got $Actual" }
    $script:checks++
    Write-Output "PASS $Label"
}
function Send-Api([string]$Method, [string]$Path, [string]$Token = '', $Body = $null) {
    $request = [System.Net.Http.HttpRequestMessage]::new([System.Net.Http.HttpMethod]::new($Method), "$BaseUrl$Path")
    if ($Token) { $request.Headers.Authorization = [System.Net.Http.Headers.AuthenticationHeaderValue]::new('Bearer', $Token) }
    if ($null -ne $Body) {
        $json = ConvertTo-Json -InputObject $Body -Depth 5 -Compress
        $request.Content = [System.Net.Http.StringContent]::new($json, [Text.Encoding]::UTF8, 'application/json')
    }
    try {
        $response = $http.SendAsync($request).GetAwaiter().GetResult()
        try {
            $json = $response.Content.ReadAsStringAsync().GetAwaiter().GetResult() | ConvertFrom-Json
            return [pscustomobject]@{ Status = [int]$response.StatusCode; Data = $json.data }
        } finally { $response.Dispose() }
    } finally { $request.Dispose() }
}
function Concurrent-Posts([string[]]$Paths, [string]$Token) {
    $requests = @()
    $tasks = @()
    try {
        foreach ($path in $Paths) {
            $request = [System.Net.Http.HttpRequestMessage]::new([System.Net.Http.HttpMethod]::Post, "$BaseUrl$path")
            $request.Headers.Authorization = [System.Net.Http.Headers.AuthenticationHeaderValue]::new('Bearer', $Token)
            $requests += $request
            $tasks += $http.SendAsync($request)
        }
        foreach ($task in $tasks) {
            $response = $task.GetAwaiter().GetResult()
            try {
                $json = $response.Content.ReadAsStringAsync().GetAwaiter().GetResult() | ConvertFrom-Json
                [pscustomobject]@{ Status = [int]$response.StatusCode; Data = $json.data }
            } finally { $response.Dispose() }
        }
    } finally { foreach ($request in $requests) { $request.Dispose() } }
}

try {
    $suffix = [guid]::NewGuid().ToString('N').Substring(0, 10)
    $password = [guid]::NewGuid().ToString('N')
    $tokens = @{}
    foreach ($kind in @('reader', 'other', 'admin')) {
        $account = "demo-$kind-$suffix"
        $registered = Send-Api POST /user/register '' @{ account = $account; password = $password; username = "Demo $kind" }
        Assert-Equal $registered.Status 200 "register $kind"
        if ($kind -eq 'admin') {
            # Only elevate the new account, with an identifier generated by this script.
            $sql = "UPDATE users SET role='ADMIN' WHERE account='$account' AND role='USER';"
            $sql | docker compose --env-file $EnvFile -p $ComposeProject exec -T mysql sh -c 'MYSQL_PWD="$MYSQL_PASSWORD" exec mysql -u"$MYSQL_USER" "$MYSQL_DATABASE"'
            if ($LASTEXITCODE -ne 0) { throw 'Local admin promotion failed' }
        }
        $login = Send-Api POST /user/login '' @{ account = $account; password = $password }
        Assert-Equal $login.Status 200 "login $kind"
        $tokens[$kind] = $login.Data.accessToken
    }
    Assert-Equal (Send-Api GET /book).Status 401 'anonymous access denied'
    Assert-Equal (Send-Api GET /admin/users $tokens.reader).Status 403 'USER cannot read admin users'
    $categoryName = "Demo-$suffix"
    Assert-Equal (Send-Api POST /category $tokens.admin @{ name = $categoryName }).Status 200 'admin creates category'
    $category = (Send-Api GET /category $tokens.admin).Data | Where-Object name -eq $categoryName
    $isbn = "DEMO-SMOKE-$suffix"
    $book = @{ title = "Smoke $suffix"; author = 'Demo Author'; isbn = $isbn; price = 10.00; stock = 1; categoryId = $category.id }
    Assert-Equal (Send-Api POST /book $tokens.reader $book).Status 403 'USER cannot create book'
    Assert-Equal (Send-Api POST /book $tokens.admin $book).Status 200 'admin creates book'
    $bookId = (Send-Api GET "/book?isbn=$isbn" $tokens.reader).Data.list[0].id
    Assert-Equal (Send-Api GET "/book/$bookId" $tokens.reader).Data.stock 1 'initial stock and cache fill'
    $book.Remove('stock')
    $book.title = "Smoke updated $suffix"
    Assert-Equal (Send-Api PUT "/book/$bookId" $tokens.admin $book).Status 200 'admin updates basic info'
    Assert-Equal (Send-Api PATCH "/book/$bookId/stock" $tokens.admin @{ delta = 2 }).Status 200 'admin applies stock delta'
    Assert-Equal (Send-Api GET "/book/$bookId" $tokens.reader).Data.stock 3 'cache invalidated after stock update'
    Assert-Equal (Send-Api PATCH "/book/$bookId/stock" $tokens.admin @{ delta = -2 }).Status 200 'prepare single copy'

    $borrowed = @(Concurrent-Posts (@("/borrow/$bookId") * 10) $tokens.reader)
    Assert-Equal @($borrowed | Where-Object Status -eq 200).Count 1 'ten concurrent borrowers: one success'
    Assert-Equal @($borrowed | Where-Object Status -eq 409).Count 9 'ten concurrent borrowers: nine conflicts'
    $recordId = ($borrowed | Where-Object Status -eq 200).Data.recordId
    Assert-Equal (Send-Api GET "/book/$bookId" $tokens.reader).Data.stock 0 'stock never negative'
    Assert-Equal (Send-Api GET "/borrow/$recordId" $tokens.other).Status 403 'other USER cannot read record'
    Assert-Equal (Send-Api POST "/borrow/$recordId/return" $tokens.other).Status 403 'other USER cannot return record'
    Assert-Equal (Send-Api GET "/borrow/$recordId" $tokens.admin).Status 200 'ADMIN can inspect record'
    Assert-Equal (Send-Api DELETE "/book/$bookId" $tokens.admin).Status 409 'active loan prevents deletion'
    $returns = @(Concurrent-Posts @("/borrow/$recordId/return", "/borrow/$recordId/return") $tokens.reader)
    Assert-Equal @($returns | Where-Object Status -eq 200).Count 1 'concurrent return: one success'
    Assert-Equal @($returns | Where-Object Status -eq 409).Count 1 'concurrent return: one conflict'
    Assert-Equal (Send-Api GET "/book/$bookId" $tokens.reader).Data.stock 1 'stock restored exactly once'
    Assert-Equal (Send-Api POST "/borrow/$recordId/return" $tokens.reader).Status 409 'repeat return rejected'
    Assert-Equal (Send-Api GET "/borrow/$recordId" $tokens.reader).Data.status 'RETURNED' 'record status persisted'
    $capacityLoan = Send-Api POST "/borrow/$bookId" $tokens.reader
    Assert-Equal $capacityLoan.Status 200 'borrow before capacity check'
    Assert-Equal (Send-Api PATCH "/book/$bookId/stock" $tokens.admin @{ delta = 2147483647 }).Status 200 'fill available stock to supported capacity'
    $capacityId = $capacityLoan.Data.recordId
    Assert-Equal (Send-Api POST "/borrow/$capacityId/return" $tokens.reader).Status 409 'return cannot overflow stock'
    Assert-Equal (Send-Api GET "/borrow/$capacityId" $tokens.reader).Data.status 'BORROWED' 'capacity conflict rolls back return status'
    Assert-Equal (Send-Api GET "/book/$bookId" $tokens.reader).Data.stock 2147483647 'capacity conflict leaves stock readable'
    Assert-Equal (Send-Api PATCH "/book/$bookId/stock" $tokens.admin @{ delta = -1 }).Status 200 'admin makes room for return'
    Assert-Equal (Send-Api POST "/borrow/$capacityId/return" $tokens.reader).Status 200 'return succeeds after capacity adjustment'
    Assert-Equal (Send-Api GET "/book/$bookId" $tokens.reader).Data.stock 2147483647 'final stock stays within Java integer range'
    Write-Output "Completed $checks checks against local MySQL/Redis. Only new demo data was added; it is retained for inspection."
} finally { $http.Dispose() }
